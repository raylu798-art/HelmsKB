import { spawnSync } from 'node:child_process'
import { cpSync, existsSync, lstatSync, realpathSync, rmSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const npmCLI = process.env.npm_execpath
if (!npmCLI) throw new Error('Run this script through npm run build:embedded.')
const result = spawnSync(process.execPath, [npmCLI, 'run', 'build:docs'], {
  cwd: root,
  stdio: 'inherit',
})
if (result.error) throw result.error
if (result.status !== 0) process.exit(result.status || 1)

const source = resolve(root, '.vitepress/dist')
const publicRoot = realpathSync(resolve(root, '../frontend/public'))
const destination = resolve(publicRoot, 'docs')
const marker = resolve(destination, 'helmskb-generated.json')
if (dirname(destination) !== publicRoot) throw new Error('Documentation output escaped frontend/public.')
if (existsSync(destination)) {
  if (lstatSync(destination).isSymbolicLink() || !existsSync(marker)) {
    throw new Error('Refusing to replace a documentation directory not generated by HelmsKB.')
  }
  rmSync(destination, { recursive: true, force: true })
}
cpSync(source, destination, { recursive: true })
writeFileSync(marker, JSON.stringify({ source: 'website-docs', generated: true }) + '\n')
console.log('HelmsKB documentation bundled at frontend/public/docs/.')
